#Numerical data types
# int daata type
nu = 8794282379
print(nu)
print(type(nu))
#float data type
fl_no = 3.14
print(fl_no)
print(type(fl_no))

# complex number
cn = 3 + 4j
print(cn)
print(type(cn))

# boolean data type
b1 = True
b2 = False
print(b1)
print(b2)
print(type(b1))
print(type(b2))
# dictionary data type
d1 = {"name":"Yogesh", "age": 20, "city":"Pune"}
print(d1)
print(type(d1))
# set data type
s1 = {1, 2, 3, 4, 5}
print(s1)
print(type(s1))
# sequence data type
# list data type
l1 = [1, 2, 3, 4, 5]
print(l1)
print(type(l1))
# tuple data type
t1 = (1, 2, 3, 4, 5)
print(t1)
print(type(t1))
# string data type
s1 = "Yogesh"
print(s1)
print(type(s1))
